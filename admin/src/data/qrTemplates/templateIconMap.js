/**
 * Returns the exact SVG logo file URL for any template
 */
export function getTemplateLogoUrl(template) {
  if (!template) return null;
  const lookupKey = (template.baseId || template.id || '').toLowerCase();
  if (TEMPLATE_LOGO_ICON_MAP[lookupKey]) {
    return TEMPLATE_LOGO_ICON_MAP[lookupKey];
  }
  const cleanId = lookupKey.replace(/^brand-/, '');
  if (TEMPLATE_LOGO_ICON_MAP[cleanId]) {
    return TEMPLATE_LOGO_ICON_MAP[cleanId];
  }
  return '/presets/internet-svgrepo-com.svg';
}
